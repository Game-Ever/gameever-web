type Key = keyof (typeof v2)['en'];

export function useV2(lang: Lang) {
  return <K extends Key>(key: K, vars: Record<string, string | number> = {}) => {
    const value = v2[lang][key] as (typeof v2)['en'][K];
    return (typeof value === 'string' ? value.replace(/\{(\w+)\}/g, (m, v) => (v in vars ? String(vars[v]) : m)) : value) as (typeof v2)['en'][K];
  };
}

export const v2url = (lang: Lang, path = '') => withBase(`v2/${lang}/${path ? path.replace(/^\/|\/$/g, '') + '/' : ''}`);
